import type { Commit, FileChange } from './types.ts'

function files(specs: readonly string[]): FileChange[] {
  return specs.map((spec) => {
    const action = spec.startsWith('M ') ? 'M' : 'A'
    return { action, path: spec.slice(2) }
  })
}

function c(
  id: string,
  year: number,
  people: string[],
  message: string,
  body: string,
  specs: readonly string[],
  approx = false,
): Commit {
  return {
    id,
    year,
    authors: people,
    message,
    body,
    files: files(specs),
    ...(approx ? { approx: true } : {}),
  }
}

